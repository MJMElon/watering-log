-- ============================================
-- PERSISTENT PAYROLL INPUT STATE
-- These hold the current bibit counts and operator names.
-- They persist across months so admin doesn't re-type every month.
-- ============================================

create table public.plot_seedlings (
  plot_name text not null,
  seedling_count integer not null default 0,
  target_per_day integer not null default 0,
  updated_at timestamp with time zone not null default now(),
  updated_by text,
  constraint plot_seedlings_pkey primary key (plot_name)
) TABLESPACE pg_default;

create table public.area_operators (
  area_code text not null,
  operator_name text not null,
  updated_at timestamp with time zone not null default now(),
  updated_by text,
  constraint area_operators_pkey primary key (area_code)
) TABLESPACE pg_default;

alter table public.plot_seedlings enable row level security;
alter table public.area_operators enable row level security;

create policy "Authenticated users can read plot_seedlings"
on public.plot_seedlings for select to authenticated using (true);
create policy "Authenticated users can insert plot_seedlings"
on public.plot_seedlings for insert to authenticated with check (true);
create policy "Authenticated users can update plot_seedlings"
on public.plot_seedlings for update to authenticated using (true);

create policy "Authenticated users can read area_operators"
on public.area_operators for select to authenticated using (true);
create policy "Authenticated users can insert area_operators"
on public.area_operators for insert to authenticated with check (true);
create policy "Authenticated users can update area_operators"
on public.area_operators for update to authenticated using (true);

