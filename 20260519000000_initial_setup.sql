-- ============================================
-- PAYROLL SNAPSHOTS
-- One row per (month) holds the saved claim breakdown for that month.
-- ============================================

create table public.payroll_snapshots (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  saved_by text null,
  snapshot_month text not null,
  snapshot_data jsonb not null,
  constraint payroll_snapshots_pkey primary key (id),
  constraint unique_snapshot_per_month unique (snapshot_month)
) TABLESPACE pg_default;

alter table public.payroll_snapshots enable row level security;

create policy "Authenticated users can read payroll snapshots"
on public.payroll_snapshots
for select
to authenticated
using (true);

