-- ============================================================
--
-- After the schema above is created on the new project, populate it
-- with data from the old project. Two practical paths:
--
-- A) CSV export/import (simplest, low row count):
--    On OLD project SQL Editor:
--        SELECT * FROM admins;           -- → export as CSV
--        SELECT * FROM watering_logs;    -- → export as CSV
--        ...etc for each table
--    On NEW project SQL Editor, use Table Editor → Import CSV per table.
--    Match the new prefixed table names:
--        admins                    → watering_admins
--        field_coordinators        → watering_field_coordinators
--        plot_seedlings            → watering_plot_seedlings
--        area_operators            → watering_area_operators
--        management_signatures     → watering_management_signatures
--        payroll_config            → watering_payroll_config
--        payroll_snapshots         → watering_payroll_snapshots
--        watering_logs             → watering_logs   (no rename)
--
-- B) pg_dump (most thorough):
--    From a machine with psql/pg_dump installed, with the OLD project's
--    direct connection string:
--        pg_dump -h <old-host> -U postgres -d postgres \
--          --schema=public --data-only \
--          --table=admins --table=field_coordinators \
--          --table=plot_seedlings --table=area_operators \
--          --table=management_signatures --table=payroll_config \
--          --table=payroll_snapshots --table=watering_logs \
--          -f data.sql
--    Then edit data.sql to rename tables to the watering_ prefixed names
--    (search/replace 'public.admins' → 'public.watering_admins' etc.),
--    and run on the NEW project.
--
-- Storage photos: download from OLD bucket via Dashboard or `supabase storage`
-- CLI, upload to NEW bucket. URLs inside watering_logs already point to
-- "watering-photos/..." paths, so they'll keep working as long as the
-- new bucket has the same name.
