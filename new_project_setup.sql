--        Events:   Delete (only)
--        Type:     Supabase Edge Functions
--        Function: delete-watering-photos
-- Once wired, ANY delete of a watering_logs row (manual, cron, app-driven)
-- auto-deletes its photos from the watering-photos bucket.


