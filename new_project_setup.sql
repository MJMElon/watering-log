-- ============================================================
-- 5. DATA RETENTION (3-year auto-prune)
-- PREREQUISITE: pg_cron must be enabled first (see top of file).
-- ============================================================

create or replace function public.watering_prune_old_logs()
returns table(deleted_logs bigint, deleted_photo_refs bigint)
language plpgsql
security definer
set search_path = public, storage
as $$
declare
    cutoff_date timestamptz;
    logs_count bigint := 0;
begin
    cutoff_date := now() - interval '3 years';

    -- Delete the old log rows. The Database Webhook on watering_logs DELETE
    -- (see Storage section above) fires the delete-watering-photos Edge Function
    -- once per row, which removes the start/end photos from the bucket via the
    -- Storage Admin API. So this single DELETE cleans both rows AND photos.
    with deleted as (
        delete from public.watering_logs
         where end_time < cutoff_date
        returning 1
    )
    select count(*) into logs_count from deleted;

    return query select logs_count, 0::bigint;
end;
$$;

revoke execute on function public.watering_prune_old_logs() from public;
revoke execute on function public.watering_prune_old_logs() from anon;
revoke execute on function public.watering_prune_old_logs() from authenticated;

-- Schedule: daily at 16:00 UTC (= 00:00 Malaysia Time, low-traffic window)
select cron.schedule(
    'watering_prune_3y',
    '0 16 * * *',
    $$select public.watering_prune_old_logs();$$
);


